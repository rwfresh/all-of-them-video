/** Paint one glyph's dots with the current fill style; (x, y) is the top left of its cell. Unknown letters: a box. */
export function glyph(g, table, ch, x, y) {
  const rows = table[ch] || (ch === ' ' ? null : table['?']);
  if (!rows) return;
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r];
    let c = 0;
    while (c < row.length) {
      if (row[c] !== '#') { c++; continue; }
      let e = c; while (e < row.length && row[e] === '#') e++;
      g.fillRect(x + c, y + r, e - c, 1);
      c = e;
    }
  }
}

/** A line of SMALL letters, one every `adv` dots. */
export function text(g, s, x, y, color, adv = 6) {
  g.fillStyle = color;
  let i = 0;
  for (const ch of s) { glyph(g, SMALL, ch, x + i * adv, y); i++; }
}

/** A number in BIG numerals, one every 8 dots. Returns its width. */
export function bigNum(g, s, x, y, color) {
  g.fillStyle = color;
  let i = 0;
  for (const ch of s) { glyph(g, BIG, ch, x + i * 8, y); i++; }
  return s.length * 8 - 1;
}
