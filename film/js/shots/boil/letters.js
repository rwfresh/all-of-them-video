// each glyph's strokes as even polylines in units; a dot is a tiny ring so that it inks as a full round spot
const GLYPH = {};
for (const [ch, strokes] of Object.entries(G)) {
  let total = 0;
  const list = strokes.map((s) => {
    const kind = s[0], nums = s.slice(1).trim().split(/[\s,]+/).map(Number), pts = [];
    for (let i = 0; i < nums.length; i += 2) pts.push([nums[i], nums[i + 1]]);
    let P;
    if (kind === '.') { const [cx, cy] = pts[0], r = 0.8; P = path(Array.from({ length: 9 }, (_, k) => [cx + r * Math.cos(k * 0.9), cy + r * Math.sin(k * 0.9)]), 0.5); P.dot = true; }
    else P = path(kind === '~' ? curve(pts, false, 8) : pts, 0.8);
    total += P.len;
    return P;
  });
  let acc = 0;
  for (const P of list) { P.t0 = acc / total; acc += P.len; P.t1 = acc / total; }
  GLYPH[ch] = list;
}
export const hasGlyph = (ch) => !!GLYPH[ch];

/**
 * Letter a string by hand. (x, y): the left edge of the first cell and the baseline.
 *   u      px a unit (3.2 = the terminal's 60 px letters)      adv   px a cell
 *   w      pen width      v   drawing number      seed   which piece of lettering this is
 *   drawn(i)   0 to 1, how much of letter i is written      pop(i)   scale of letter i about its foot
 *   slant  lean to the right      wob   how much each letter sits off the line (1 = normal)
 *   xf     a transform for the whole piece of lettering (a frame that is turned, a caption that bounces)
 */
export function letter(g, str, x, y, o = {}) {
  const u = o.u ?? 3.2, adv = o.adv ?? u * 11.25, w = o.w ?? u * 1.8, wide = o.wide ?? 1.16, v = o.v ?? 0, seed = o.seed ?? 3, wob = (o.wob ?? 1) * calm();
  const n = Math.min(str.length, o.n ?? str.length), boil = o.boil ?? 0.34 * u, slant = o.slant ?? 0;
  for (let i = 0; i < n; i++) {
    const ch = str[i];
    if (ch === ' ') continue;
    const d = o.drawn ? o.drawn(i) : 1;
    if (d <= 0) continue;
    const glyph = GLYPH[ch];
    const cx = x + i * adv + adv / 2;
    if (!glyph) { g.fillStyle = o.color || INK; g.font = `400 ${u * 20.7}px "JetBrains Mono"`; g.textAlign = 'center'; g.textBaseline = 'alphabetic'; g.fillText(ch, cx, y); g.textAlign = 'left'; continue; }
    const hs = seed * 13.7 + i * 7.31 + ch.charCodeAt(0) * 0.173;
    // the hand's character (fixed) and the redrawing's error (changes with v)
    const rot = ((hash(hs) - 0.5) * 0.085 + vn(v * 3.1, hs + 1) * 0.014) * wob;
    const k = (o.pop ? o.pop(i) : 1) * u * (1 + (hash(hs + 2) - 0.5) * 0.07 * wob);
    const ox = cx + (vn(v * 2.3, hs + 3) * 0.55 + (hash(hs + 6) - 0.5) * 1.6) * wob;
    const oy = y + ((hash(hs + 4) - 0.5) * 2.4 + vn(v * 2.9, hs + 5) * 0.55) * wob;
    const c = Math.cos(rot), s = Math.sin(rot);
    // unit (gx, gy), y up, about the letter's foot (6, 0)  ->  screen
    const kx = k * wide;
    let tf = [c * kx, s * kx, (c * slant + s) * k, (s * slant - c) * k, ox - 6 * c * kx, oy - 6 * s * kx];
    if (o.xf) tf = xmul(o.xf, tf);
    for (let j = 0; j < glyph.length; j++) {
      const P = glyph[j];
      const to = d >= 1 ? 1 : (d - P.t0) / (P.t1 - P.t0);
      if (to <= 0) break;
      ink(g, P, {
        w: (P.dot ? w * 0.8 : w) * (o.heavy ? 1.32 : 1), tf, v, seed: hs + j * 3.3, to, press: P.dot ? 0 : 0.3,
        boil: boil / k, boilLen: 7, rough: 0.16 * wob, roughLen: 9, taper: P.dot ? 0 : 3.2, color: o.color, alpha: o.alpha,
      });
    }
  }
}
